// Makes each hero portrait's blur placeholder from the photo itself
// (data/portraitBlur.ts): a 12px-wide, tiny JPEG inlined as a data URL, so the circle shows a
// soft version of the real portrait while the photo loads, never black. One entry per path in
// data/portraits.ts. Run after a portrait is added or changes: node scripts/gen-portrait-blur.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import sharp from 'sharp'

const paths = [...readFileSync('data/portraits.ts', 'utf8').matchAll(/'(\/hero\/[^']+)'/g)].map((m) => m[1])
if (paths.length === 0) throw new Error('no portraits found in data/portraits.ts')

const lines = []
for (const path of paths) {
  const buf = await sharp(`public${path}`).resize(12, 12, { fit: 'cover' }).jpeg({ quality: 60 }).toBuffer()
  lines.push(`  '${path}': 'data:image/jpeg;base64,${buf.toString('base64')}',`)
  console.log(`${path}: ${buf.length} bytes`)
}
writeFileSync(
  'data/portraitBlur.ts',
  `// Generated by scripts/gen-portrait-blur.mjs from the files in data/portraits.ts. Do not edit by hand.
export const PORTRAIT_BLUR: Record<string, string> = {
${lines.join('\n')}
}
`
)
