// Builds components/ui/BoldMap/mapData.generated.ts, the bold map's data, from
// scripts/map-data/ (Natural Earth, public domain: the states, the neighbours,
// the Great Lakes and a list of places; and a mean elevation per map cell).
// Usage: node scripts/gen-map-data.mjs
//
// The page never needs the outlines themselves, only which cell of the grid is
// the United States, a neighbour or water, so that is worked out here, once,
// and the outlines stay out of the bundle.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const read = (name) => JSON.parse(readFileSync(join(root, 'scripts/map-data', name), 'utf8'))
const G = read('geo.json')
const R = read('relief.json')
const ROUTES = new Set(read('routes.json'))

// The Albers plane the elevations were sampled on (keep in step with geo.ts).
const rad = Math.PI / 180
const p1 = 29.5 * rad,
  p2 = 45.5 * rad,
  l0 = -96 * rad,
  f0 = 37.5 * rad
const n = (Math.sin(p1) + Math.sin(p2)) / 2
const C = Math.cos(p1) ** 2 + 2 * n * Math.sin(p1)
const rho0 = Math.sqrt(C - 2 * n * Math.sin(f0)) / n
const PITCH = (R.x1 - R.x0) / R.cols
const cellOf = ([lon, lat]) => {
  const rho = Math.sqrt(C - 2 * n * Math.sin(lat * rad)) / n
  const th = n * (lon * rad - l0)
  return [(rho * Math.sin(th) - R.x0) / PITCH, (-(rho0 - rho * Math.cos(th)) - R.y0) / PITCH]
}

// Non-zero winding, as a canvas fills a path of several rings.
const project = (rings) => rings.map((ring) => ring.map(cellOf))
const inside = (rings, x, y) => {
  let wn = 0
  for (const ring of rings) {
    for (let k = 0; k < ring.length; k++) {
      const [ax, ay] = ring[k]
      const [bx, by] = ring[(k + 1) % ring.length]
      const side = (bx - ax) * (y - ay) - (x - ax) * (by - ay)
      if (ay <= y) {
        if (by > y && side > 0) wn++
      } else if (by <= y && side < 0) wn--
    }
  }
  return wn !== 0
}
const us = project(G.states.flatMap((s) => s.r))
const neighbours = project(G.neighbours)
const lakes = project(G.lakes)

// 0 water, 1 the United States, 2 a neighbour (Canada, Mexico, the islands).
const kinds = new Uint8Array(R.cols * R.rows)
for (let j = 0; j < R.rows; j++) {
  for (let i = 0; i < R.cols; i++) {
    const x = i + 0.5,
      y = j + 0.5
    if (inside(lakes, x, y)) continue
    kinds[j * R.cols + i] = inside(us, x, y) ? 1 : inside(neighbours, x, y) ? 2 : 0
  }
}

const places = G.places.map((p) => {
  const name = p.n.replace(/,?\s+D\.C\./, '').replace(/\s+/g, ' ')
  return [name, p.s, p.lon, p.lat, p.pop, ROUTES.has(`${name} ${p.s}`) ? 1 : 0]
})
const missing = [...ROUTES].filter((r) => !places.some((p) => `${p[0]} ${p[1]}` === r))
if (missing.length)
  throw new Error(`routes.json names places not in geo.json: ${missing.join(', ')}`)

const out = `// Generated by scripts/gen-map-data.mjs from scripts/map-data/ (Natural Earth,
// public domain). Do not edit by hand: change the inputs and run the script.

/** The grid: the Albers plane's bounds and one cell's size, in plane units. */
export const GRID = ${JSON.stringify({ cols: R.cols, rows: R.rows, x0: R.x0, y0: R.y0, pitch: PITCH })} as const

/** One byte per cell, row by row: 0 water, 1 the United States, 2 a neighbour. Base64. */
export const KINDS = '${Buffer.from(kinds).toString('base64')}'

/** One byte per cell, row by row: mean elevation, sqrt-coded (metres = (b / 255)^2 * 4000). Base64. */
export const RELIEF = '${R.h}'

/** [name, state, longitude, latitude, population, 1 when the map's own routes may go there] */
export type PlaceRow = readonly [string, string, number, number, number, 0 | 1]

export const PLACES: readonly PlaceRow[] = [
${places.map((p) => `  ${JSON.stringify(p)},`).join('\n')}
]
`
writeFileSync(join(root, 'components/ui/BoldMap/mapData.generated.ts'), out)
console.log(
  `cells: ${kinds.filter((k) => k === 1).length} US, ${kinds.filter((k) => k === 2).length} neighbour; places: ${places.length}, routes: ${ROUTES.size}`
)
